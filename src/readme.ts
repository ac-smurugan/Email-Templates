/**
 * `pnpm build` runs this after the build: rewrites the part of README.md between the markers with
 * a table per email (and per PDF report) of its placeholders, from each template's `fields`, so
 * the README can't drift from the templates.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PDFS } from './pdf/index.ts';
import { GROUPS, type Fields } from './template.ts';
import { TEMPLATES } from './templates/index.ts';

const README = fileURLToPath(new URL('../README.md', import.meta.url));
const START = '<!-- placeholders:start (generated by src/readme.ts; edit the templates, not this) -->';
const END = '<!-- placeholders:end -->';

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function table(fields: Fields): string {
  const rows = Object.entries(fields).map(
    ([name, f]) => `| \`${name}\` | ${f.isNew ? '**New**' : 'Today'} | ${f.optional ? 'Optional' : 'Required'} | ${cell(f.about)} |`,
  );
  return ['| Placeholder | Backend | Use | What it holds |', '|---|---|---|---|', ...rows].join('\n');
}

function generated(): string {
  const out: string[] = [];
  const newCount = TEMPLATES.filter((t) => Object.values(t.fields).some((f) => f.isNew)).length;
  out.push(
    `${TEMPLATES.length} emails and ${PDFS.length} PDF reports. ${newCount} emails use at least one **New** placeholder: a value the backend has to start supplying.`,
  );
  for (const group of GROUPS) {
    const emails = TEMPLATES.filter((t) => t.group === group);
    if (!emails.length) continue;
    out.push(`### ${group}`);
    for (const t of emails) {
      out.push(
        `#### ${t.name} (\`${t.id}\`)`,
        `- **Subject:** ${cell(t.subject)}`,
        `- **Who / when:** ${cell(t.who)}; ${cell(t.when)}`,
        `- **Today:** ${cell(t.source)}`,
        `- **Kind:** ${t.kind}${t.engine === 'substitution' ? ', filled by plain `${name}` substitution (no Velocity)' : ''}`,
        '',
        table(t.fields),
      );
    }
  }
  if (PDFS.length) {
    out.push('### PDF reports');
    for (const p of PDFS) out.push(`#### ${p.name} (\`${p.id}\`)`, `- **Today:** ${cell(p.source)}`, `- **When:** ${cell(p.when)}`, '', table(p.fields));
  }
  return out.join('\n\n');
}

const readme = readFileSync(README, 'utf8');
const [before, rest] = readme.split(START);
const after = rest?.split(END)[1];
if (before === undefined || after === undefined) throw new Error('README.md is missing the placeholder markers');
writeFileSync(README, `${before}${START}\n\n${generated()}\n\n${END}${after}`);
console.log('README.md placeholder tables updated.');
